// v0.36: reinpay rules history, offline. Signed, chained entries; edits, removals and reordering are caught.
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";
process.env.REINPAY_HOME = mkdtempSync(join(tmpdir(), "reinpay-history-"));
const H = await import("../src/history.js");
let pass = 0, fail = 0;
const check = (label, cond, info = "") => { cond ? pass++ : fail++; console.log(`${cond ? "PASS" : "FAIL"} ${label}${info ? ` (${info})` : ""}`); };
const acct = privateKeyToAccount(generatePrivateKey()), other = privateKeyToAccount(generatePrivateKey());
const W = "0x000000000000000000000000000000000000dEaD";
const c0 = { rules: { daily: { ETH: 0.005 }, approveAbove: { ETH: 0.001 } }, payees: [], notify: { kind: "telegram", token: "123:SECRET", chat: "42" } };
const c1 = { ...c0, rules: { ...c0.rules, daily: { ETH: "0.01" } } };
const c2 = { ...c1, payees: [{ name: "Weather API", address: W, isContract: false, addedAt: "2026-11-20T00:00:00Z" }] };
const c3 = { ...c2, payees: [] };
let h = [];
for (const [i, c] of [c0, c1, c2, c3].entries()) h.push(await H.nextEntry(h, c, acct, `2026-11-20T05:0${i}:00Z`));
check("four seals, four entries; the first says it is the first", h.length === 4 && h[0].changes[0].path === "(first entry)");
check("a change is recorded as before → after", h[1].changes.length === 1 && h[1].changes[0].path === "rules.daily.ETH" && h[1].changes[0].before === 0.005 && h[1].changes[0].after === "0.01");
check("sealing again with no change adds nothing", (await H.nextEntry(h, c3, acct)) === null);
const lines = H.historyLines(h).join("\n");
check("a payee added or removed whole reads as one line", lines.includes(`payee added    Weather API  ${W}`) && lines.includes(`payee removed  Weather API  ${W}`), lines.split("\n").filter((l) => l.includes("payee")).join(" | "));
check("the notification token is never written into the history, not even in the snapshot", !JSON.stringify(h).includes("SECRET") && /\(set, [0-9a-f]{8}\)/.test(JSON.stringify(h[0].body)));
const tok = await H.nextEntry(h, { ...c3, notify: { ...c3.notify, token: "999:OTHER" } }, acct);
check("a new token still shows as a change, as two fingerprints", tok.changes.length === 1 && tok.changes[0].path === "notify.token" && /^\(set, /.test(tok.changes[0].before) && tok.changes[0].before !== tok.changes[0].after && !JSON.stringify(tok).includes("OTHER"));
check("an intact history checks out against the wallet and the config sealed now", (await H.verifyHistory(h, acct.address, c3)).ok);
const edited = structuredClone(h); edited[1].changes[0].after = "1";
check("an edited change is caught", (await H.verifyHistory(edited, acct.address)).problems.some((p) => p.startsWith("entry 2") && p.includes("does not match its signature")));
const removed = [h[0], h[2], h[3]];
check("a removed entry is caught by the chain", (await H.verifyHistory(removed, acct.address)).problems.some((p) => p.includes("does not follow the entry before it")));
const swapped = [h[0], h[2], h[1], h[3]];
check("reordered entries are caught", !(await H.verifyHistory(swapped, acct.address)).ok);
const body = structuredClone(h); body[3].body.rules.daily.ETH = "5";
check("an edited snapshot is caught", (await H.verifyHistory(body, acct.address)).problems.some((p) => p.includes("edited after it was signed")));
check("entries checked against another wallet fail", !(await H.verifyHistory(h, other.address)).ok);
check("config sealed now that is not the last entry is reported", (await H.verifyHistory(h, acct.address, c0)).problems.some((p) => p.includes("not the last entry")));
const e = await H.recordSeal(c0, acct), e2 = await H.recordSeal(c0, acct);
check("recordSeal writes one entry and skips an unchanged seal", e && e2 === null && H.loadHistory().length === 1);
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
