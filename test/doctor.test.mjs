// reinpay doctor, offline: config checks and the full checkup against a pretend RPC client.
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";
process.env.REINPAY_HOME = mkdtempSync(join(tmpdir(), "reinpay-doctor-"));
const D = await import("../src/doctor.js");
const C = await import("../src/config.js");
const K = await import("../src/keystore.js");
const { sealConfig } = await import("../src/seal.js");
let pass = 0, fail = 0;
const check = (label, cond, info = "") => { cond ? pass++ : fail++; console.log(`${cond ? "PASS" : "FAIL"} ${label}${info ? ` (${info})` : ""}`); };
const by = (list, n) => list.find((c) => c.name === n);
const DEAD = "0x000000000000000000000000000000000000dEaD", FAKE = "0x0000" + "1".repeat(32) + "dead";

check("node 22.12 is enough, 22.11 is not, 23.0 is", D.nodeOk("22.12.0") && !D.nodeOk("22.11.9") && D.nodeOk("23.0.0"));
let cc = D.configChecks(C.DEFAULT_CONFIG, null);
check("no payees: warn with the command to add one", by(cc, "payees").level === "warn" && /payee add/.test(by(cc, "payees").fix));
cc = D.configChecks({ ...C.DEFAULT_CONFIG, payees: [{ name: "Burn", address: DEAD }, { name: "Fake", address: FAKE }] }, null);
check("two lookalike payees: fail, both named", by(cc, "payees").level === "fail" && /Burn and Fake/.test(by(cc, "payees").detail));
cc = D.configChecks({ ...C.DEFAULT_CONFIG, payees: [{ name: "Burn", address: DEAD }, { name: "Fake", address: FAKE, lookalikeConfirmed: "Burn" }] }, null);
check("a lookalike you confirmed in the terminal: warn, not fail", by(cc, "payees").level === "warn");
cc = D.configChecks({ ...C.DEFAULT_CONFIG, rules: { ...C.DEFAULT_CONFIG.rules, daily: { USDG: 25 } }, payees: [{ name: "Burn", address: DEAD }] }, null);
check("a payee may receive ETH but ETH has no daily budget: warn", by(cc, "daily budgets").level === "warn" && /ETH/.test(by(cc, "daily budgets").detail));
cc = D.configChecks({ ...C.DEFAULT_CONFIG, rules: { ...C.DEFAULT_CONFIG.rules, daily: { USDG: 25 } }, payees: [{ name: "Burn", address: DEAD, tokens: ["USDG"] }] }, null);
check("payee limited to USDG with a USDG budget: ok", by(cc, "daily budgets").level === "ok" && by(cc, "payees").level === "ok");

const fake = (o = {}) => ({ getChainId: async () => o.chain ?? 4663, getGasPrice: async () => o.gas ?? 10_000_000n, getBalance: async () => o.bal ?? 10n ** 16n, ...(o.down ? { getChainId: async () => { throw new Error("fetch failed"); } } : {}) });
let all = await D.doctor({ client: fake() });
check("no wallet yet: fail with reinpay init", by(all, "wallet").level === "fail" && by(all, "wallet").fix === "reinpay init");
const pk = generatePrivateKey(); const me = K.writeKeystore(pk, "throwaway-test-passphrase");
C.saveConfig(await sealConfig({ ...C.DEFAULT_CONFIG, payees: [{ name: "Burn", address: DEAD }] }, privateKeyToAccount(pk)));
all = await D.doctor({ client: fake() });
check("healthy setup: 10 checks, none failing", all.length === 10 && !all.some((c) => c.level === "fail"), all.map((c) => `${c.name}:${c.level}`).join(" "));
check("sealed config: ok", by(all, "config seal").level === "ok");
check("locked with autosend off: ok", by(all, "unlock").level === "ok");
check("0.01 ETH covers many fees: ok", by(all, "gas money").level === "ok");
check("wrong chain id: fail", by(await D.doctor({ client: fake({ chain: 1 }) }), "chain").level === "fail");
check("RPC down: fail, no throw", by(await D.doctor({ client: fake({ down: true }) }), "rpc").level === "fail");
check("zero ETH: fail with the wallet address to fund", (() => 0)() === 0 && by(await D.doctor({ client: fake({ bal: 0n }) }), "gas money").fix.includes(me));
check("ETH for only a few payments: warn", by(await D.doctor({ client: fake({ bal: 80_000n * 10_000_000n * 3n }) }), "gas money").level === "warn");
const c2 = C.loadConfig(); c2.payees.push({ name: "Sneaky", address: "0x00000000000000000000000000000000DeaDBeef" }); C.saveConfig(c2);
check("config.json edited by hand: seal fails", by(await D.doctor({ client: fake() }), "config seal").level === "fail");
const c3 = C.loadConfig(); c3.rules.autoSend = true; C.saveConfig(c3);
check("autosend on but locked: warn", by(await D.doctor({ client: fake() }), "unlock").level === "warn");
K.unlock("throwaway-test-passphrase", 60_000);
check("unlocked with an end time: ok", by(await D.doctor({ client: fake() }), "unlock").level === "ok");
K.unlock("throwaway-test-passphrase", 0);
check("unlocked with no end time: warn", by(await D.doctor({ client: fake() }), "unlock").level === "warn");
K.lock();
const Fz = await import("../src/freeze.js");
check("not frozen, breaker on: brakes ok", by(await D.doctor({ client: fake() }), "brakes").level === "ok");
Fz.freeze({ by: "breaker", reason: "test trip" });
const fb = by(await D.doctor({ client: fake() }), "brakes");
check("frozen: brakes warn, says who froze it and how to unfreeze", fb.level === "warn" && /breaker/.test(fb.detail) && /unfreeze/.test(fb.fix));
Fz.unfreeze();
const txt = D.doctorText(all);
check("text output ends with the summary line", /10 checks · 0 to fix/.test(txt));
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
