// v0.14: looking across every agent's wallet. Offline; HOME points at a throwaway folder so ~/.reinpay is fake.
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { execFileSync } from "node:child_process";
import { generatePrivateKey } from "viem/accounts";
const fakeHome = mkdtempSync(join(tmpdir(), "reinpay-fleet-"));
process.env.HOME = fakeHome; delete process.env.REINPAY_HOME; delete process.env.REINPAY_PROFILE;
const FL = await import("../src/fleet.js");
const K = await import("../src/keystore.js");
const RC = await import("../src/receipts.js");
const F = await import("../src/freeze.js");
let pass = 0, fail = 0;
const check = (label, cond, info = "") => { cond ? pass++ : fail++; console.log(`${cond ? "PASS" : "FAIL"} ${label}${info ? ` (${info})` : ""}`); };
const DEAD = "0x000000000000000000000000000000000000dEaD";
const make = (name, receipts) => { process.env.REINPAY_PROFILE = name === "default" ? "" : name; const a = K.writeKeystore(generatePrivateKey(), "throwaway-test-passphrase"); for (const [status, usdg] of receipts) RC.addReceipt({ by: "agent", wallet: a, payee: "Burn", payeeAddress: DEAD, token: "USDG", amount: String(usdg), amountRaw: String(usdg * 1e6), status, rule: "x", reason: "x" }); return a; };
make("default", [["sent", 3], ["needs_approval", 2]]);
make("research", [["sent", 7], ["blocked", 1], ["blocked", 1]]);
make("trader", []);
process.env.REINPAY_PROFILE = "";
check("profile names: default first, then the others in order", FL.profileNames().join() === "default,research,trader");
const rows = await FL.eachProfile(() => FL.summary());
const by = (n) => rows.find((r) => r.profile === n);
check("default: 3 USDG sent, 1 waiting", by("default").today.USDG.sent === "3 USDG" && by("default").waiting === 1);
check("research: 7 USDG sent, 2 blocked today", by("research").today.USDG.sent === "7 USDG" && by("research").blockedToday === 2);
check("each wallet keeps its own address", new Set(rows.map((r) => r.address)).size === 3);
check("looking across profiles leaves REINPAY_PROFILE as it was", process.env.REINPAY_PROFILE === "");
const txt = FL.fleetText(rows);
check("the overview text counts wallets and waiting payments", /3 wallets · 0 frozen · 1 payments waiting/.test(txt));
await FL.eachProfile(async (n) => { if (n !== "trader") F.freeze({ by: "owner", reason: "test" }); return {}; });
const rows2 = await FL.eachProfile(() => FL.summary());
check("freezing across profiles: two frozen, one not", rows2.filter((r) => r.frozen).length === 2 && !rows2.find((r) => r.profile === "trader").frozen);
check("the overview shows FROZEN", /FROZEN \(owner\)/.test(FL.fleetText(rows2)));
const cli = execFileSync(process.execPath, [new URL("../bin/reinpay.js", import.meta.url).pathname, "profiles", "--status"], { env: { ...process.env, HOME: fakeHome, REINPAY_PROFILE: "" }, encoding: "utf8" });
check("reinpay profiles --status prints every wallet", /research/.test(cli) && /trader/.test(cli) && /3 wallets · 2 frozen/.test(cli));
const fz = execFileSync(process.execPath, [new URL("../bin/reinpay.js", import.meta.url).pathname, "freeze", "--all", "going away"], { env: { ...process.env, HOME: fakeHome, REINPAY_PROFILE: "" }, encoding: "utf8" });
check("reinpay freeze --all freezes the one that was not frozen", /trader\s+frozen/.test(fz) && /research\s+already frozen/.test(fz));
let e = null; try { process.env.REINPAY_HOME = "/tmp/x"; await FL.eachProfile(() => ({})); } catch (x) { e = x; } delete process.env.REINPAY_HOME;
check("with REINPAY_HOME set, looking across profiles is refused", /REINPAY_HOME is set/.test(e?.message || ""));
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
