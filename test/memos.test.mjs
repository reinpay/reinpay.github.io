// v0.28: memo privacy, offline.
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
process.env.REINPAY_HOME = mkdtempSync(join(tmpdir(), "reinpay-memos-"));
const RC = await import("../src/receipts.js");
const S = await import("../src/statement.js");
const B = await import("../src/books.js");
const N = await import("../src/notify.js");
await import("../src/chain.js");
let pass = 0, fail = 0;
const check = (label, cond, info = "") => { cond ? pass++ : fail++; console.log(`${cond ? "PASS" : "FAIL"} ${label}${info ? ` (${info})` : ""}`); };
const W = "0x00000000000000000000000000000000DeaDBeef", DEAD = "0x000000000000000000000000000000000000dEaD";
const r = RC.addReceipt({ by: "agent", wallet: W, payee: "Burn", payeeAddress: DEAD, token: "USDG", amount: "1", amountRaw: "1000000", status: "sent", txHash: "0x" + "ab".repeat(32), memo: "client ACME project falcon" });
check("statement with memos keeps them", S.buildStatement([RC.getReceipt(r.id)], { wallet: W }).payments[0].memo === "client ACME project falcon");
check("statement --no-memos leaves them out", S.buildStatement([RC.getReceipt(r.id)], { wallet: W, memos: false }).payments[0].memo === "");
check("shared receipt --no-memos leaves it out", S.receiptProof(RC.getReceipt(r.id), { wallet: W, memos: false }).payments[0].memo === "");
const month = new Date().toISOString().slice(0, 7);
check("books --no-memos leaves them out", B.monthRows(RC.allReceipts(), month, { memos: false }).rows[0].memo === "");
check("a notification includes the memo by default", /memo "client ACME/.test(N.message({ ...r, rule: "x", reason: "x" })));
let sent = null; const f = async (u, o) => { sent = JSON.parse(o.body); return { ok: true, status: 200 }; };
await N.notifyOwner({ ...r, rule: "x", reason: "x" }, { cfg: { notify: { type: "webhook", url: "https://example.com/h", hideMemos: true } }, fetch: f });
check("notify memos off: neither the text nor the webhook body carries the memo", sent.memo === null && !/ACME/.test(sent.text));
RC.redactMemo(r.id, "client asked");
const red = RC.getReceipt(r.id);
check("redact replaces the memo for good and notes why", red.memo === "[redacted]" && red.history.some((h) => /redacted by the owner: client asked/.test(h.note)));
check("redacting twice changes nothing more", RC.redactMemo(r.id).history.length === red.history.length);
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
