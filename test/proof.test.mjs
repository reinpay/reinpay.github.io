// v0.16: payee proofs, offline.
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";
process.env.REINPAY_HOME = mkdtempSync(join(tmpdir(), "reinpay-proof-"));
const PF = await import("../src/proof.js");
const R = await import("../src/rules.js");
await import("../src/chain.js");
let pass = 0, fail = 0;
const check = (label, cond, info = "") => { cond ? pass++ : fail++; console.log(`${cond ? "PASS" : "FAIL"} ${label}${info ? ` (${info})` : ""}`); };
const payeeKey = privateKeyToAccount(generatePrivateKey()), other = privateKeyToAccount(generatePrivateKey()), wallet = privateKeyToAccount(generatePrivateKey());
const payee = { name: "Weather API", address: payeeKey.address };
const msg = PF.proofMessage(payee, wallet.address);
check("the message names the payee, its address and the wallet", msg.includes(payee.address) && msg.includes('"Weather API"') && msg.includes(wallet.address));
const good = await payeeKey.signMessage({ message: msg });
check("a signature from the payee's own key proves it", (await PF.checkProof(payee, wallet.address, good)).ok);
check("a signature from another key does not", !(await PF.checkProof(payee, wallet.address, await other.signMessage({ message: msg }))).ok);
check("a proof made for another wallet does not count here", !(await PF.checkProof(payee, other.address, good)).ok);
check("a proof made for another payee name does not count", !(await PF.checkProof({ ...payee, name: "GPU credits" }, wallet.address, good)).ok);
check("garbage is refused with a reason", /not a 65-byte signature/.test((await PF.checkProof(payee, wallet.address, "0x1234")).reason));
const rules = { daily: { USDG: 25 }, maxPerPayment: { USDG: 10 }, approveAbove: { USDG: 5 }, repeatGuardMinutes: 0, requireProven: true };
const d1 = R.decide({ rules, receipts: [], request: { payee, token: "USDG", amountRaw: 1_000_000n } });
check("require-proven: an unproven payee waits for the owner", d1.status === "needs_approval" && d1.rule === "unproven payee" && /payee challenge/.test(d1.reason));
check("require-proven: a proven payee goes through", R.decide({ rules, receipts: [], request: { payee: { ...payee, proof: { sig: good, at: "x" } }, token: "USDG", amountRaw: 1_000_000n } }).status === "allowed");
check("require-proven: hard limits still block first", R.decide({ rules, receipts: [], request: { payee, token: "USDG", amountRaw: 20_000_000n } }).status === "blocked");
check("require-proven: a contract payee (it cannot sign) is not held for this", R.decide({ rules, receipts: [], request: { payee: { ...payee, isContract: true }, token: "USDG", amountRaw: 1_000_000n } }).status === "allowed");
check("rule off: unproven payees go through", R.decide({ rules: { ...rules, requireProven: false }, receipts: [], request: { payee, token: "USDG", amountRaw: 1_000_000n } }).status === "allowed");
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
